SELECT u.ID, u.USER_NAME, r.ID AS ROLE_ID, r.NAME AS ROLE_NAME
FROM IDM_USERS u
JOIN IDM_USER_ROLE_ASSIGNMENTS ura ON ura.USER_ID = u.ID
JOIN IDM_ROLES r ON r.ID = ura.ROLE_ID
WHERE u.USER_NAME IN ('h05.user', 'donvi.user')
ORDER BY u.USER_NAME, r.NAME;

SELECT r.NAME AS ROLE_NAME, p.PERM_CODE
FROM IDM_ROLES r
JOIN IDM_ROLE_PERMISSIONS rp ON rp.ROLE_ID = r.ID
JOIN IDM_PERMISSIONS p ON p.ID = rp.PERMISSION_ID
WHERE r.NAME IN ('QUAN_LY', 'CAP_TINH')
  AND p.PERM_CODE LIKE 'bien_dong_bao_cao:%'
ORDER BY r.NAME, p.PERM_CODE;

SELECT p.ID, p.PERM_CODE, p.MODULE, p.ACTION
FROM IDM_PERMISSIONS p
WHERE p.PERM_CODE LIKE 'bien_dong_bao_cao:%'
ORDER BY p.PERM_CODE;
EXIT
