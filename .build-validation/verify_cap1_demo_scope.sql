SELECT d.CAP_DON_VI, COUNT(DISTINCT d.ID) SO_DON_VI
FROM REF_DON_VI d
JOIN RPT_BAO_CAO_SNAPSHOT s ON s.DON_VI_ID = d.ID
WHERE s.KY_BAO_CAO_ID IN (325, 326)
  AND s.TRANG_THAI IN (2, 3)
  AND d.IS_ACTIVE = 1
  AND d.DELETED_AT IS NULL
GROUP BY d.CAP_DON_VI
ORDER BY d.CAP_DON_VI;
