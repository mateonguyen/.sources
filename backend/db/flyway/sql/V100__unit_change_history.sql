-- Luu danh tinh don vi theo thoi diem va quan he ke thua sau sap xep.
-- Migration nay co the chay lai an toan sau mot lan Oracle DDL bi loi giua chung.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'REF_DV_VERSION';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE REF_DV_VERSION (
                ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                DON_VI_ID NUMBER(19) NOT NULL,
                MA_DON_VI NVARCHAR2(50) NOT NULL,
                TEN_DON_VI NVARCHAR2(200) NOT NULL,
                CAP_DON_VI NVARCHAR2(20),
                CHE_DO_NHAP_LIEU NVARCHAR2(20) NOT NULL,
                PARENT_ID NUMBER(19),
                IS_ACTIVE NUMBER(1) NOT NULL,
                VALID_FROM TIMESTAMP NOT NULL,
                VALID_TO TIMESTAMP,
                CONSTRAINT FK_DVV_UNIT FOREIGN KEY (DON_VI_ID) REFERENCES REF_DON_VI(ID)
            )';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_DVV_UNIT_TIME';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_DVV_UNIT_TIME ON REF_DV_VERSION(DON_VI_ID, VALID_FROM, VALID_TO)';
    END IF;
END;
/

INSERT INTO REF_DV_VERSION (
    DON_VI_ID,
    MA_DON_VI,
    TEN_DON_VI,
    CAP_DON_VI,
    CHE_DO_NHAP_LIEU,
    PARENT_ID,
    IS_ACTIVE,
    VALID_FROM)
SELECT
    d.ID,
    d.MA_DON_VI,
    d.TEN_DON_VI,
    d.CAP_DON_VI,
    CAST(NVL(d.CHE_DO_NHAP_LIEU, 'TU_NHAP') AS NVARCHAR2(20)),
    d.PARENT_ID,
    d.IS_ACTIVE,
    NVL(d.CREATED_AT, SYSTIMESTAMP)
FROM REF_DON_VI d
WHERE NOT EXISTS (
    SELECT 1
    FROM REF_DV_VERSION v
    WHERE v.DON_VI_ID = d.ID
);

