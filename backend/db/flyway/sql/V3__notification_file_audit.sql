-- Notification, generic files, and immutable audit log
CREATE TABLE THONG_BAO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DON_VI_ID NUMBER(19) NULL,
    USER_ID NUMBER(19) NULL,
    LOAI_THONG_BAO NUMBER(10) NOT NULL,
    TIEU_DE NVARCHAR2(255) NOT NULL,
    NOI_DUNG NVARCHAR2(2000) NOT NULL,
    DA_DOC NUMBER(1) DEFAULT 0 NOT NULL,
    DOC_LUC_UTC TIMESTAMP NULL,
    LIEN_KY_ID NUMBER(19) NULL,
    LIEN_YEU_CAU_ID NUMBER(19) NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE FILE_DINH_KEM (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DON_VI_ID NUMBER(19) NOT NULL,
    ENTITY_TYPE NVARCHAR2(150) NOT NULL,
    ENTITY_ID NUMBER(19) NOT NULL,
    FILE_NAME NVARCHAR2(255) NOT NULL,
    FILE_PATH NVARCHAR2(500) NOT NULL,
    FILE_SIZE NUMBER(19) NOT NULL,
    MIME_TYPE NVARCHAR2(100) NOT NULL,
    UPLOADED_BY NUMBER(19) NOT NULL,
    UPLOADED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    DELETED_AT_UTC TIMESTAMP NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL
);

CREATE INDEX IX_FILE_DINH_KEM_ENTITY ON FILE_DINH_KEM (ENTITY_TYPE, ENTITY_ID);

CREATE TABLE SYSTEM_LOG (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19) NULL,
    DON_VI_ID NUMBER(19) NULL,
    ACTION_TYPE NUMBER(10) NOT NULL,
    TABLE_NAME NVARCHAR2(200) NULL,
    RECORD_ID NUMBER(19) NULL,
    BEFORE_DATA NCLOB NULL,
    AFTER_DATA NCLOB NULL,
    IP_ADDRESS NVARCHAR2(50) NULL,
    USER_AGENT NVARCHAR2(1000) NULL,
    ROUTE NVARCHAR2(500) NULL,
    LOGGED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_SYSTEM_LOG_LOGGED_AT_UTC ON SYSTEM_LOG (LOGGED_AT_UTC);
