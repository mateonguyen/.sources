-- V66: create refresh-token session storage used by auth/login, refresh, logout, and session management.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'IDM_REFRESH_TOKEN_SESSIONS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE IDM_REFRESH_TOKEN_SESSIONS (
                ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                USER_ID NUMBER(19) NOT NULL,
                REFRESH_TOKEN_HASH NVARCHAR2(500) NOT NULL,
                DEVICE_ID NVARCHAR2(255) NOT NULL,
                DEVICE_USER_AGENT NVARCHAR2(500) NOT NULL,
                DEVICE_IP_ADDRESS NVARCHAR2(50) NOT NULL,
                DEVICE_NAME NVARCHAR2(255) NULL,
                ISSUED_AT TIMESTAMP NOT NULL,
                EXPIRES_AT TIMESTAMP NOT NULL,
                LAST_USED_AT TIMESTAMP NULL,
                IS_REVOKED NUMBER(1) DEFAULT 0 NOT NULL,
                REVOKED_AT TIMESTAMP NULL,
                REVOCATION_REASON NVARCHAR2(255) NULL,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CONSTRAINT FK_IDM_REFRESH_TOKEN_SESSIONS_USER
                    FOREIGN KEY (USER_ID) REFERENCES IDM_USERS(ID)
            )';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
