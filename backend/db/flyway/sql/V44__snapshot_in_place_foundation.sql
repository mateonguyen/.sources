CREATE OR REPLACE PROCEDURE PRC_ROLLUP_XA_PHUONG_SNAPSHOT (
  P_KY_BAO_CAO_CODE IN NVARCHAR2,
  P_DON_VI_ID IN NUMBER
) AS
  V_TOTAL_ROWS NUMBER := 0;
BEGIN
  SELECT COUNT(1)
    INTO V_TOTAL_ROWS
    FROM BIZ_DAO_TAO_HOC_VIEN
   WHERE IS_LATEST = 1
     AND DON_VI_ID = P_DON_VI_ID
     AND (KY_BAO_CAO_CODE = P_KY_BAO_CAO_CODE OR KY_BAO_CAO_CODE IS NULL);

  UPDATE RPT_SNAPSHOT_BATCH
     SET AGGREGATE_ROWS = NVL(AGGREGATE_ROWS, 0) + V_TOTAL_ROWS,
         UPDATED_AT = SYSTIMESTAMP
   WHERE DON_VI_ID = P_DON_VI_ID
     AND STATUS = 'RUNNING';
END;
