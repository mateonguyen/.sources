     AND (P_DON_VI_ID IS NULL OR DON_VI_ID = P_DON_VI_ID)
     AND KY_BAO_CAO_CODE IS NULL;

  UPDATE BIZ_CAMERA_QUAN_LY
     SET KY_BAO_CAO_CODE = P_KY_BAO_CAO_CODE,
