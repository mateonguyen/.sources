CREATE OR REPLACE PROCEDURE PRC_MARK_SNAPSHOT_IN_PLACE (
  P_KY_BAO_CAO_CODE IN NVARCHAR2,
  P_SNAPSHOT_BATCH_ID IN NUMBER,
  P_DON_VI_ID IN NUMBER DEFAULT NULL
) AS
BEGIN
  UPDATE BIZ_ATTT_HTTT_VAN_HANH
     SET KY_BAO_CAO_CODE = P_KY_BAO_CAO_CODE,
         SNAPSHOT_VERSION = NVL(SNAPSHOT_VERSION, 0),
         SNAPSHOT_CREATED_AT = SYSTIMESTAMP,
         SNAPSHOT_BATCH_ID = P_SNAPSHOT_BATCH_ID
   WHERE IS_LATEST = 1
     AND (P_DON_VI_ID IS NULL OR DON_VI_ID = P_DON_VI_ID)
     AND KY_BAO_CAO_CODE IS NULL;

  UPDATE BIZ_ATTT_HTTT_DAU_TU
     SET KY_BAO_CAO_CODE = P_KY_BAO_CAO_CODE,
         SNAPSHOT_VERSION = NVL(SNAPSHOT_VERSION, 0),
         SNAPSHOT_CREATED_AT = SYSTIMESTAMP,
         SNAPSHOT_BATCH_ID = P_SNAPSHOT_BATCH_ID
