     AND KY_BAO_CAO_CODE IS NULL;

  UPDATE BIZ_CAMERA_THUC_TRANG
     SET KY_BAO_CAO_CODE = P_KY_BAO_CAO_CODE,
         SNAPSHOT_VERSION = NVL(SNAPSHOT_VERSION, 0),
