-- Reporting period and snapshot source-of-truth model
CREATE TABLE KY_BAO_CAO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    KY_CODE NVARCHAR2(20) NOT NULL,
    NAM NUMBER(10) NOT NULL,
    QUY NUMBER(10) NOT NULL,
    TRANG_THAI NUMBER(10) NOT NULL,
    NGAY_BAT_DAU DATE NULL,
    NGAY_KET_THUC DATE NULL,
    GHI_CHU NVARCHAR2(2000) NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL
);

CREATE UNIQUE INDEX UX_KY_BAO_CAO_KY_CODE ON KY_BAO_CAO (KY_CODE);

CREATE TABLE KY_TRANG_THAI_DON_VI (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    KY_BAO_CAO_ID NUMBER(19) NOT NULL,
    DON_VI_ID NUMBER(19) NOT NULL,
    TRANG_THAI NUMBER(10) NOT NULL,
    NGAY_XAC_NHAN_UTC TIMESTAMP NULL,
    CONFIRMED_BY NUMBER(19) NULL,
    NGAY_MO_LAI_UTC TIMESTAMP NULL,
    MO_LAI_BY NUMBER(19) NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL,
    CONSTRAINT FK_KY_TRANG_THAI_DON_VI_KY FOREIGN KEY (KY_BAO_CAO_ID) REFERENCES KY_BAO_CAO(ID),
    CONSTRAINT FK_KY_TRANG_THAI_DON_VI_DON_VI FOREIGN KEY (DON_VI_ID) REFERENCES DON_VI(ID)
);

CREATE UNIQUE INDEX UX_KY_TRANG_THAI_DON_VI_KY_DONVI ON KY_TRANG_THAI_DON_VI (KY_BAO_CAO_ID, DON_VI_ID);

CREATE TABLE BAO_CAO_SNAPSHOT (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    KY_BAO_CAO_ID NUMBER(19) NOT NULL,
    DON_VI_ID NUMBER(19) NOT NULL,
    TRANG_THAI NUMBER(10) NOT NULL,
    PHIEN_BAN NUMBER(10) NOT NULL,
    SNAPSHOT_JSON NCLOB NOT NULL,
    SUMMARY_JSON NCLOB NULL,
    SUBMITTED_AT_UTC TIMESTAMP NULL,
    SUBMITTED_BY NUMBER(19) NULL,
    LOCKED_AT_UTC TIMESTAMP NULL,
    LOCKED_BY NUMBER(19) NULL,
    GHI_CHU NVARCHAR2(2000) NULL,
    DELETED_AT_UTC TIMESTAMP NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL,
    CONSTRAINT FK_BAO_CAO_SNAPSHOT_KY FOREIGN KEY (KY_BAO_CAO_ID) REFERENCES KY_BAO_CAO(ID),
    CONSTRAINT FK_BAO_CAO_SNAPSHOT_DON_VI FOREIGN KEY (DON_VI_ID) REFERENCES DON_VI(ID)
);

CREATE UNIQUE INDEX UX_BAO_CAO_SNAPSHOT_KY_DONVI_VER ON BAO_CAO_SNAPSHOT (KY_BAO_CAO_ID, DON_VI_ID, PHIEN_BAN);

CREATE TABLE BAO_CAO_FILE (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    BAO_CAO_SNAPSHOT_ID NUMBER(19) NOT NULL,
    FILE_NAME NVARCHAR2(255) NOT NULL,
    FILE_PATH NVARCHAR2(500) NOT NULL,
    MIME_TYPE NVARCHAR2(100) NOT NULL,
    FILE_SIZE NUMBER(19) NOT NULL,
    LOAI_FILE NVARCHAR2(50) DEFAULT 'pdf' NOT NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL,
    CONSTRAINT FK_BAO_CAO_FILE_SNAPSHOT FOREIGN KEY (BAO_CAO_SNAPSHOT_ID) REFERENCES BAO_CAO_SNAPSHOT(ID)
);
