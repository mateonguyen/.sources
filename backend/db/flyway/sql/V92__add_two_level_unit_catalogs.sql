    'LOAI_VAN_BAN',
    'CO_QUAN_BAN_HANH',
    'LINH_VUC_VAN_BAN'
);

-- Quyen rieng cho danh muc cap don vi. Khong dung codes:update de tranh
-- trao quyen sua bo chuan toan he thong cho can bo nhap lieu dia phuong.
INSERT INTO IDM_PERMISSIONS (ID, PERM_CODE, MODULE, ACTION, MO_TA)
SELECT
    (SELECT COALESCE(MAX(ID), 3000) + 1 FROM IDM_PERMISSIONS),
    'danh_muc_don_vi:read',
    'danh_muc_don_vi',
    'read',
    'Danh mục đơn vị : Xem'
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM IDM_PERMISSIONS WHERE PERM_CODE = 'danh_muc_don_vi:read'
);

INSERT INTO IDM_PERMISSIONS (ID, PERM_CODE, MODULE, ACTION, MO_TA)
SELECT
    (SELECT COALESCE(MAX(ID), 3000) + 1 FROM IDM_PERMISSIONS),
    'danh_muc_don_vi:update',
    'danh_muc_don_vi',
    'update',
    'Danh mục đơn vị : Cập nhật'
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM IDM_PERMISSIONS WHERE PERM_CODE = 'danh_muc_don_vi:update'
);

INSERT INTO IDM_ROLE_PERMISSIONS (ROLE_ID, PERMISSION_ID)
SELECT r.ID, p.ID
FROM IDM_ROLES r
JOIN IDM_PERMISSIONS p
  ON p.PERM_CODE IN ('danh_muc_don_vi:read', 'danh_muc_don_vi:update')
WHERE r.NORMALIZED_NAME IN ('QUAN_LY', 'CAP_TINH', 'CAP_XA')
  AND NOT EXISTS (
    SELECT 1
    FROM IDM_ROLE_PERMISSIONS rp
    WHERE rp.ROLE_ID = r.ID
      AND rp.PERMISSION_ID = p.ID
  );
