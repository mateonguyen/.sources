-- V92: Danh muc 2 tang: chuan toan he thong + tuy chinh theo don vi.

ALTER TABLE CODES ADD (
    ALLOW_UNIT_CUSTOMIZATION NUMBER(1) DEFAULT 0 NOT NULL
);

ALTER TABLE CODE_VALUES ADD (
    DON_VI_ID NUMBER(19) NULL,
    REPORTING_VALUE_ID NUMBER(19) NULL,
    IS_REQUIRED NUMBER(1) DEFAULT 0 NOT NULL
);

ALTER TABLE CODE_VALUES ADD CONSTRAINT FK_CODE_VALUE_DON_VI
    FOREIGN KEY (DON_VI_ID) REFERENCES REF_DON_VI(ID);
ALTER TABLE CODE_VALUES ADD CONSTRAINT FK_CODE_VALUE_REPORTING
    FOREIGN KEY (REPORTING_VALUE_ID) REFERENCES CODE_VALUES(ID);
ALTER TABLE CODE_VALUES ADD CONSTRAINT CK_CODE_VALUE_REQUIRED
    CHECK (IS_REQUIRED IN (0, 1));
CREATE INDEX IX_CODE_VALUE_DON_VI ON CODE_VALUES (DON_VI_ID, CODE_ID);

ALTER TABLE REF_LOAI_THIET_BI ADD (
    DON_VI_ID NUMBER(19) NULL,
    REPORTING_LOAI_ID NUMBER(19) NULL,
    IS_REQUIRED NUMBER(1) DEFAULT 0 NOT NULL
);

ALTER TABLE REF_LOAI_THIET_BI ADD CONSTRAINT FK_LTB_DON_VI
    FOREIGN KEY (DON_VI_ID) REFERENCES REF_DON_VI(ID);
ALTER TABLE REF_LOAI_THIET_BI ADD CONSTRAINT FK_LTB_REPORTING
    FOREIGN KEY (REPORTING_LOAI_ID) REFERENCES REF_LOAI_THIET_BI(ID);
ALTER TABLE REF_LOAI_THIET_BI ADD CONSTRAINT CK_LTB_REQUIRED
    CHECK (IS_REQUIRED IN (0, 1));
CREATE INDEX IX_LTB_DON_VI ON REF_LOAI_THIET_BI (DON_VI_ID, PARENT_ID);

CREATE TABLE REF_DANH_MUC_DON_VI (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DON_VI_ID NUMBER(19) NOT NULL,
    DANH_MUC_LOAI NVARCHAR2(20) NOT NULL,
    DANH_MUC_KEY NVARCHAR2(100) NOT NULL,
    ITEM_ID NUMBER(19) NOT NULL,
    IS_VISIBLE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL,
    CONSTRAINT FK_DMDV_DON_VI FOREIGN KEY (DON_VI_ID) REFERENCES REF_DON_VI(ID),
    CONSTRAINT CK_DMDV_LOAI CHECK (DANH_MUC_LOAI IN ('CODE', 'DEVICE')),
    CONSTRAINT CK_DMDV_VISIBLE CHECK (IS_VISIBLE IN (0, 1)),
    CONSTRAINT UQ_DMDV_ITEM UNIQUE (DON_VI_ID, DANH_MUC_LOAI, DANH_MUC_KEY, ITEM_ID)
);
CREATE INDEX IX_DMDV_LOOKUP ON REF_DANH_MUC_DON_VI
    (DON_VI_ID, DANH_MUC_LOAI, DANH_MUC_KEY);

