-- Core identity and organizational structure
CREATE TABLE USERS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_NAME NVARCHAR2(256),
    NORMALIZED_USER_NAME NVARCHAR2(256),
    EMAIL NVARCHAR2(256),
    NORMALIZED_EMAIL NVARCHAR2(256),
    EMAIL_CONFIRMED NUMBER(1) DEFAULT 0 NOT NULL,
    PASSWORD_HASH NVARCHAR2(2000),
    SECURITY_STAMP NVARCHAR2(2000),
    CONCURRENCY_STAMP NVARCHAR2(2000),
    PHONE_NUMBER NVARCHAR2(50),
    PHONE_NUMBER_CONFIRMED NUMBER(1) DEFAULT 0 NOT NULL,
    TWO_FACTOR_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    LOCKOUT_END TIMESTAMP NULL,
    LOCKOUT_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    ACCESS_FAILED_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    HO_TEN NVARCHAR2(200) NOT NULL,
    DON_VI_ID NUMBER(19) NOT NULL,
    MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 1 NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    LAST_LOGIN_AT_UTC TIMESTAMP NULL,
    REFRESH_TOKEN_HASH NVARCHAR2(500) NULL,
    SO_DIEN_THOAI NVARCHAR2(50) NULL,
    DELETED_AT_UTC TIMESTAMP NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL
);

CREATE UNIQUE INDEX UX_USERS_NORMALIZED_USER_NAME ON USERS (NORMALIZED_USER_NAME);
CREATE INDEX IX_USERS_NORMALIZED_EMAIL ON USERS (NORMALIZED_EMAIL);

CREATE TABLE ROLES (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME NVARCHAR2(256),
    NORMALIZED_NAME NVARCHAR2(256),
    CONCURRENCY_STAMP NVARCHAR2(2000),
    TEN_ROLE NVARCHAR2(200) NOT NULL,
    MO_TA NVARCHAR2(500) NULL,
    IS_SYSTEM NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL
);

CREATE UNIQUE INDEX UX_ROLES_NORMALIZED_NAME ON ROLES (NORMALIZED_NAME);

CREATE TABLE PERMISSIONS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PERM_CODE NVARCHAR2(150) NOT NULL,
    MODULE NVARCHAR2(100) NOT NULL,
    ACTION NVARCHAR2(100) NOT NULL,
    MO_TA NVARCHAR2(500) NULL
);

CREATE UNIQUE INDEX UX_PERMISSIONS_PERM_CODE ON PERMISSIONS (PERM_CODE);

CREATE TABLE ROLE_PERMISSIONS (
    ROLE_ID NUMBER(19) NOT NULL,
    PERMISSION_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_ROLE_PERMISSIONS PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERMISSIONS_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID),
    CONSTRAINT FK_ROLE_PERMISSIONS_PERMISSION FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS(ID)
);

CREATE TABLE USER_ROLE_ASSIGNMENTS (
    USER_ID NUMBER(19) NOT NULL,
    ROLE_ID NUMBER(19) NOT NULL,
    DON_VI_ID NUMBER(19) NOT NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    CONSTRAINT PK_USER_ROLE_ASSIGNMENTS PRIMARY KEY (USER_ID, ROLE_ID, DON_VI_ID),
    CONSTRAINT FK_USER_ROLE_ASSIGNMENTS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_USER_ROLE_ASSIGNMENTS_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID)
);

CREATE TABLE LOAI_DON_VI (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    MA_LOAI NVARCHAR2(50) NOT NULL,
    TEN_LOAI NVARCHAR2(200) NOT NULL,
    CAP_DON_VI NUMBER(10) NOT NULL,
    THU_TU NUMBER(10) NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL
);

CREATE UNIQUE INDEX UX_LOAI_DON_VI_MA_LOAI ON LOAI_DON_VI (MA_LOAI);

CREATE TABLE DON_VI (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    MA_DON_VI NVARCHAR2(50) NOT NULL,
    TEN_DON_VI NVARCHAR2(200) NOT NULL,
    TEN_VIET_TAT NVARCHAR2(50) NULL,
    LOAI_DON_VI_ID NUMBER(19) NOT NULL,
    PARENT_ID NUMBER(19) NULL,
    DIA_CHI NVARCHAR2(500) NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    DELETED_AT_UTC TIMESTAMP NULL,
    CREATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT_UTC TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19) NULL,
    UPDATED_BY NUMBER(19) NULL,
    CONSTRAINT FK_DON_VI_LOAI FOREIGN KEY (LOAI_DON_VI_ID) REFERENCES LOAI_DON_VI(ID),
    CONSTRAINT FK_DON_VI_PARENT FOREIGN KEY (PARENT_ID) REFERENCES DON_VI(ID)
);

CREATE UNIQUE INDEX UX_DON_VI_MA_DON_VI ON DON_VI (MA_DON_VI);
