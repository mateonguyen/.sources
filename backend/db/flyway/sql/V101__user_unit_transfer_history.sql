-- Luu lich su dieu chuyen tai khoan giua cac don vi.
-- Dung cac khoi idempotent de co the tiep tuc neu Oracle DDL bi loi giua chung.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'IDM_USER_UNIT_HISTORY';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE IDM_USER_UNIT_HISTORY (
                ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                USER_ID NUMBER(19) NOT NULL,
                SOURCE_DV_ID NUMBER(19) NOT NULL,
                TARGET_DV_ID NUMBER(19) NOT NULL,
                CHANGE_ID NUMBER(19),
                TRANSFERRED_AT TIMESTAMP NOT NULL,
                TRANSFERRED_BY NUMBER(19),
                CONSTRAINT FK_UUH_USER FOREIGN KEY (USER_ID) REFERENCES IDM_USERS(ID),
                CONSTRAINT FK_UUH_SOURCE FOREIGN KEY (SOURCE_DV_ID) REFERENCES REF_DON_VI(ID),
                CONSTRAINT FK_UUH_TARGET FOREIGN KEY (TARGET_DV_ID) REFERENCES REF_DON_VI(ID),
                CONSTRAINT FK_UUH_CHANGE FOREIGN KEY (CHANGE_ID) REFERENCES REF_DV_CHANGE(ID)
            )';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_UUH_USER_TIME';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_UUH_USER_TIME ON IDM_USER_UNIT_HISTORY(USER_ID, TRANSFERRED_AT)';
    END IF;
END;
/
