-- V7: Create standardized shared-code tables

CREATE TABLE CODES (
    ID           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODE         NVARCHAR2(100) NOT NULL,
    NAME         NVARCHAR2(255) NOT NULL,
    DESCRIPTION  NVARCHAR2(1000) NULL,
    SORT_ORDER   NUMBER(10) DEFAULT 0 NOT NULL,
    IS_ACTIVE    NUMBER(1) DEFAULT 1 NOT NULL,
    IS_SYSTEM    NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   NUMBER(19) NULL,
    UPDATED_BY   NUMBER(19) NULL,
    CONSTRAINT UQ_CODES_CODE UNIQUE (CODE),
    CONSTRAINT CK_CODES_IS_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_CODES_IS_SYSTEM CHECK (IS_SYSTEM IN (0, 1)),
    CONSTRAINT CK_CODES_SORT_ORDER CHECK (SORT_ORDER >= 0)
);

CREATE TABLE CODE_VALUES (
    ID           NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODE_ID      NUMBER(19) NOT NULL,
    VALUE        NVARCHAR2(100) NOT NULL,
    NAME         NVARCHAR2(255) NOT NULL,
    DESCRIPTION  NVARCHAR2(1000) NULL,
    SORT_ORDER   NUMBER(10) DEFAULT 0 NOT NULL,
    IS_ACTIVE    NUMBER(1) DEFAULT 1 NOT NULL,
    IS_SYSTEM    NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   NUMBER(19) NULL,
    UPDATED_BY   NUMBER(19) NULL,
    CONSTRAINT FK_CODE_VALUES_CODE_ID FOREIGN KEY (CODE_ID) REFERENCES CODES (ID),
    CONSTRAINT UQ_CODE_VALUES_CODE_ID_VALUE UNIQUE (CODE_ID, VALUE),
    CONSTRAINT CK_CODE_VALUES_IS_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_CODE_VALUES_IS_SYSTEM CHECK (IS_SYSTEM IN (0, 1)),
    CONSTRAINT CK_CODE_VALUES_SORT_ORDER CHECK (SORT_ORDER >= 0)
);

CREATE INDEX IX_CODE_VALUES_CODE_ID ON CODE_VALUES (CODE_ID);
