SELECT r.ID, p.ID
FROM IDM_ROLES r
CROSS JOIN IDM_PERMISSIONS p
WHERE r.NAME IN ('QUAN_LY', 'CAP_TINH', 'CAP_XA', 'LANH_DAO', 'VIEWER')
  AND p.PERM_CODE = 'bien_dong_bao_cao:read'
  AND NOT EXISTS (
      SELECT 1 FROM IDM_ROLE_PERMISSIONS rp
      WHERE rp.ROLE_ID = r.ID AND rp.PERMISSION_ID = p.ID
  );

