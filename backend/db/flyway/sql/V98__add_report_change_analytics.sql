DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM ALL_TABLES
     WHERE TABLE_NAME = 'RPT_SNAPSHOT_METRIC';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE RPT_SNAPSHOT_METRIC (
                ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                SNAPSHOT_ID NUMBER(19) NOT NULL,
                SNAPSHOT_BATCH_ID NUMBER(19) NOT NULL,
                KY_BAO_CAO_ID NUMBER(19) NOT NULL,
                REPORT_DON_VI_ID NUMBER(19) NOT NULL,
                SOURCE_DON_VI_ID NUMBER(19) NOT NULL,
                MODULE_CODE NVARCHAR2(80) NOT NULL,
                METRIC_CODE NVARCHAR2(120) NOT NULL,
                VALUE NUMBER(24,6) DEFAULT 0 NOT NULL,
                NUMERATOR NUMBER(24,6) NULL,
                DENOMINATOR NUMBER(24,6) NULL,
                METRIC_VERSION NUMBER(10) DEFAULT 1 NOT NULL,
                CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                CREATED_BY NUMBER(19) NULL,
                UPDATED_BY NUMBER(19) NULL,
                CONSTRAINT FK_RPT_METRIC_SNAPSHOT FOREIGN KEY (SNAPSHOT_ID) REFERENCES RPT_BAO_CAO_SNAPSHOT(ID) ON DELETE CASCADE,
                CONSTRAINT FK_RPT_METRIC_BATCH FOREIGN KEY (SNAPSHOT_BATCH_ID) REFERENCES RPT_SNAPSHOT_BATCH(ID),
                CONSTRAINT FK_RPT_METRIC_KY FOREIGN KEY (KY_BAO_CAO_ID) REFERENCES RPT_KY_BAO_CAO(ID),
                CONSTRAINT FK_RPT_METRIC_REPORT_DV FOREIGN KEY (REPORT_DON_VI_ID) REFERENCES REF_DON_VI(ID),
                CONSTRAINT FK_RPT_METRIC_SOURCE_DV FOREIGN KEY (SOURCE_DON_VI_ID) REFERENCES REF_DON_VI(ID)
            )';
    END IF;
END;
/

